#!/usr/bin/env python3
"""Convert the Calculator shutdown artwork to a portrait MONO1_MSB asset.

This follows Shake Gallery's verified static UI conversion: EXIF correction,
aspect-preserving contain, white letterboxing, threshold 180, and no dithering.
"""

from pathlib import Path

try:
    from PIL import Image, ImageOps
except ImportError as error:
    raise SystemExit("Pillow is required to regenerate this asset") from error


IMAGE_SIZE = (480, 800)
FRAME_SIZE = IMAGE_SIZE[0] * IMAGE_SIZE[1] // 8
BLACK_THRESHOLD = 180


def prepare(source: Image.Image) -> tuple[Image.Image, str]:
    image = ImageOps.exif_transpose(source).convert("RGB")
    if image.size == IMAGE_SIZE:
        return image, "kept original 480x800 composition"

    resampling = getattr(Image, "Resampling", Image).LANCZOS
    fitted = ImageOps.contain(image, IMAGE_SIZE, method=resampling)
    canvas = Image.new("RGB", IMAGE_SIZE, "white")
    offset = ((IMAGE_SIZE[0] - fitted.width) // 2,
              (IMAGE_SIZE[1] - fitted.height) // 2)
    canvas.paste(fitted, offset)
    return canvas, f"fit without crop: {image.size} -> {fitted.size}"


def format_bytes(data: bytes) -> str:
    return "\n".join(
        "    " + ", ".join(f"0x{value:02X}" for value in data[offset:offset + 12]) + ","
        for offset in range(0, len(data), 12)
    )


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    source_path = root / "assets" / "Calculator.png"
    header_path = root / "main" / "assets" / "calculator_wallpaper.h"
    cpp_path = root / "main" / "assets" / "calculator_wallpaper.cpp"

    with Image.open(source_path) as source:
        canvas, sizing_note = prepare(source)
        grayscale = ImageOps.grayscale(canvas)
        monochrome = grayscale.point(
            lambda value: 0 if value < BLACK_THRESHOLD else 255,
            mode="1",
        )
        framebuffer = monochrome.tobytes()

    if len(framebuffer) != FRAME_SIZE:
        raise RuntimeError(f"expected {FRAME_SIZE} bytes, got {len(framebuffer)}")

    header_path.write_text(
        "// Generated by tools/convert_calculator_wallpaper.py. Do not edit.\n"
        "#pragma once\n\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n\n"
        "inline constexpr int kCalculatorWallpaperWidth = 480;\n"
        "inline constexpr int kCalculatorWallpaperHeight = 800;\n"
        f"inline constexpr size_t kCalculatorWallpaperSize = {FRAME_SIZE}U;\n"
        "extern const uint8_t kCalculatorWallpaper[kCalculatorWallpaperSize];\n",
        encoding="utf-8",
        newline="\n",
    )
    cpp_path.write_text(
        "// Generated by tools/convert_calculator_wallpaper.py. Do not edit.\n"
        '#include "calculator_wallpaper.h"\n\n'
        "alignas(4) const uint8_t kCalculatorWallpaper[kCalculatorWallpaperSize] = {\n"
        + format_bytes(framebuffer)
        + "\n};\n\n"
        + f"static_assert(sizeof(kCalculatorWallpaper) == {FRAME_SIZE}U);\n",
        encoding="utf-8",
        newline="\n",
    )

    print(f"Source -> {source_path}")
    print(f"Sizing -> {sizing_note}")
    print(f"Framebuffer -> {cpp_path} ({len(framebuffer)} bytes)")
    print(f"Binarization -> fixed threshold {BLACK_THRESHOLD}, no dithering")
    print("Format -> portrait 480x800 MONO1_MSB, bit 0=black, bit 1=white")


if __name__ == "__main__":
    main()
